# ── file access ──────────────────────────────────────────────────────────────


def tracked_files(root: pathlib.Path) -> tuple[str, ...]:
    """Every file git tracks, as repository-relative POSIX paths."""
    result = subprocess.run(
        ["git", "ls-files", "-z"], cwd=root, capture_output=True, check=True, text=True
    )
    return tuple(sorted(entry for entry in result.stdout.split("\0") if entry))


def read_text(root: pathlib.Path, path: str) -> str | None:
    """Read a tracked file as text, or `None` if it is binary or unreadable."""
    try:
        data = (root / path).read_bytes()
    except OSError:
        return None
    if b"\0" in data:
        return None
    return data.decode("utf-8", errors="replace")


def _is_documentation(path: str) -> bool:
    name = path.rsplit("/", 1)[-1]
    suffix = ("." + name.rsplit(".", 1)[-1]) if "." in name else ""
    return suffix in DOCUMENTATION_SUFFIXES or name in DOCUMENTATION_NAMES


def _line_of(text: str, offset: int) -> int:
    return text.count("\n", 0, offset) + 1


def _scan_rules(
    root: pathlib.Path,
    check: str,
    rules: Iterable[Rule],
    paths: Iterable[str],
    *,
    accounted: object = None,
) -> CheckResult:
    """Apply a rule set to a set of tracked files, honouring the line marker."""
    result = CheckResult(check)
    rules = tuple(rules)
    for path in paths:
        if is_canary(path):
            continue
        text = read_text(root, path)
        if text is None:
            continue
        marked = marked_lines(text)
        for rule in rules:
            for match in rule.pattern.finditer(text):
                line = _line_of(text, match.start())
                if line in marked:
                    result.skips.append(
                        Skip(path, line, MARKER_REASON, f"suppressed {check}/{rule.name}")
                    )
                    continue
                if accounted is not None:
                    reason = accounted(root, path, text, rule, match)  # type: ignore[operator]
                    if reason is not None:
                        result.skips.append(Skip(path, line, reason[0], reason[1]))
                        continue
                result.findings.append(
                    Finding(check, path, line, rule.name, rule.detail, rule.hint)
                )
    return result.fail()


# ── check 1 — secrets ────────────────────────────────────────────────────────

_DIFF_SPLIT = re.compile(r"(?m)^diff --git ")
_NEW_PATH = re.compile(r"(?m)^\+\+\+ b/(?P<path>.*)$")
_OLD_PATH = re.compile(r"(?m)^--- a/(?P<path>.*)$")


def history_segments(patch: str) -> list[tuple[str | None, str]]:
    """Split `git log -p --all` into `(path, text)`, one per file diff.

    The tree sweep skips the canary directory by exact path; the history sweep has
    to skip it by the same path or the committed fixtures make it permanently red
    — and a check that is always red is a check nobody reads. Splitting the patch
    is what makes the *same* allowlist apply to both.

    The first segment is everything before the first diff: commit headers and
    commit messages. Its path is `None`, so it is **never** exempt. A secret
    pasted into a commit message is a secret in the history.

    The path is read from the `+++ b/…` line, which runs to the end of the line
    and so survives a path with spaces; a deletion (`+++ /dev/null`) falls back to
    the `--- a/…` line.
    """
    parts = _DIFF_SPLIT.split(patch)
    segments: list[tuple[str | None, str]] = [(None, parts[0])]
    for part in parts[1:]:
        match = _NEW_PATH.search(part) or _OLD_PATH.search(part)
        path = match.group("path").strip() if match else None
        segments.append((path, part))
    return segments


def scan_secrets(root: pathlib.Path, *, history: bool = False) -> CheckResult:
    """Token shapes and credential assignments, over the tree and the history.

    The history sweep is `git log -p --all`, because an unreachable object is not
    a deleted one and this repository's history was erased and re-created once
    already. It is CI's job (`--history`); the pre-commit hook skips it for speed.
    """
    result = _scan_rules(root, "secrets", SECRET_RULES, tracked_files(root))
    if not history:
        result.note = "tree only — pass --history for the full-history sweep"
        return result.fail()

    completed = subprocess.run(
        ["git", "log", "-p", "--all"], cwd=root, capture_output=True, text=True, errors="replace"
    )
    if completed.returncode != 0:
        result.findings.append(
            Finding(
                "secrets",
                "<history>",
                None,
                "history-unreadable",
                "`git log -p --all` failed, so the history sweep did not run",
                "run the scan inside a git working tree with the full history fetched",
            )
        )
        return result.fail()

    patch = completed.stdout
    counts: dict[str, int] = {}
    exempt: dict[str, int] = {}
    for path, segment in history_segments(patch):
        for rule in SECRET_RULES:
            hits = len(rule.pattern.findall(segment))
            if not hits:
                continue
            if path is not None and is_canary(path):
                exempt[path] = exempt.get(path, 0) + hits
            else:
                counts[rule.name] = counts.get(rule.name, 0) + hits
    for rule in SECRET_RULES:
        hits = counts.get(rule.name, 0)
        if hits:
            result.findings.append(
                Finding(
                    "secrets",
                    "<history>",
                    None,
                    rule.name,
                    f"{hits} occurrence(s) of {rule.detail} in `git log -p --all`",
                    rule.hint,
                )
            )
    for path, hits in sorted(exempt.items()):
        result.skips.append(
            Skip(
                path,
                None,
                "canary-directory",
                f"{hits} occurrence(s) in the history of this file",
            )
        )
    result.note = f"tree + history ({len(patch)} patch bytes)"
    return result.fail()


# ── check 2 — PHI shapes ─────────────────────────────────────────────────────

_GIT_OBJECT_CACHE: dict[tuple[str, str], bool] = {}
_LOCKFILE_SIZE = re.compile(r"size\s*=\s*$")


def _is_git_object(root: pathlib.Path, candidate: str) -> bool:
    """Whether an all-digit run names a real object in this repository.

    A short commit hash that happens to be all digits is not a medical record
    number, and this repository records one in every completed roadmap row. The
    test is mechanical and fails closed: a run git cannot resolve is a finding.
    """
    key = (str(root), candidate)
    if key in _GIT_OBJECT_CACHE:
        return _GIT_OBJECT_CACHE[key]
    completed = subprocess.run(
        ["git", "rev-parse", "--verify", "--quiet", candidate + "^{object}"],
        cwd=root,
        capture_output=True,
        text=True,
    )
    _GIT_OBJECT_CACHE[key] = completed.returncode == 0
    return _GIT_OBJECT_CACHE[key]


def _accounted_phi(
    root: pathlib.Path, path: str, text: str, rule: Rule, match: re.Match[str]
) -> tuple[str, str] | None:
    """The two accounted-for digit runs, and the project's own contact address.

    Each is narrow, mechanical and inventoried in the scan summary. None of them
    is a path exemption: a leak in one of these files would still be reported by
    every other rule.
    """
    if rule.name == "email-address":
        if match.group(0) == PROJECT_CONTACT:
            return ("project-contact", "the address this repository already publishes (OD-7)")
        return None
    if rule.name != "mrn-shaped-digit-run":
        return None
    if _LOCKFILE_SIZE.search(text[max(0, match.start() - 12) : match.start()]):
        return ("lockfile-byte-size", "a `size =` value in a machine-generated resolver lockfile")
    if _is_git_object(root, match.group(0)):
        return (
            "git-object-id",
            "an all-digit abbreviated object id that resolves in this repository",
        )
    return None


def scan_phi(root: pathlib.Path) -> CheckResult:
    """PHI-shaped patterns across tracked files and fixtures, plus the D-36 rule."""
    result = _scan_rules(root, "phi", PHI_RULES, tracked_files(root), accounted=_accounted_phi)
    result.findings.extend(_scenario_attestations(root))
    scenarios = scenario_files(root)
    result.note = (
        f"{len(scenarios)} scenario fixture(s) checked for the D-36 attestation"
        if scenarios
        else "no scenario fixtures yet (the D-36 attestation check becomes live at EP-25)"
    )
    return result.fail()


