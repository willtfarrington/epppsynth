"""The nine leak-prevention scanners (EP-6), as importable functions.

Every brief before EP-6 ran these checks by hand, once, and pasted the output
into a completion note. That does not scale and it does not survive a tired
session. Here they are enforcement: one function per check, each returning
findings rather than raising, so that one run reports the whole picture.

The nine checks, by id:

===================  ==============================================================
``secrets``          token shapes and credential assignments, tree and full history
``phi``              MRN / DOB / NPI / SSN / phone / email / street-address shapes
``protected-text``   corpus paths in history, the D-74 budget, chapter-title runs
``identity``         user-profile paths, UNC paths, foreign drives, account, host
``roots``            the index and model roots outside documentation
``rights``           EP-5's licence, source-reference and verbatim rules
``badge``            the README badge resolves to a fully ticked evidence file
``modality``         the retired-modality stem (D-4, owner ruling OD-10)
``ledger``           shared passages with private planning state (D-2, OD-3)
===================  ==============================================================

A tenth id, ``allowlist``, is not a leak check: it is this module checking its
own rule-definition allowlist, and it reports a marker that suppressed nothing.
An exemption for a line that does not need one is a hole waiting for a future
edit.

**These scanners are defense in depth. They are not proof that nothing leaked.**
The proof is the pre-publication review packet in
`epppsynth/docs/pre-publication-checklist.md`, performed by a human, recorded
with a date and a commit hash.

**Split literals.** Every rule literal in this file is assembled from fragments
across a ``+``, so that the file defining a rule does not match the rule it
defines. EP-0 set the convention for prose; it applies to code for the same
reason, and it is why this module needs no exemption of its own.

**No finding prints matched text.** A finding is a check id, a path, a line, a
rule name and a static explanation of the rule. Printing the match would make a
CI log the very artifact the secrets check exists to prevent.
"""

