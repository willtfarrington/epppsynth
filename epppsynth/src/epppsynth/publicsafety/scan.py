@dataclass(frozen=True)
class Rule:
    name: str
    pattern: re.Pattern[str]
    detail: str
    hint: str = ""


def _rule(name: str, pattern: str, detail: str, hint: str = "", flags: int = 0) -> Rule:
    return Rule(name, re.compile(pattern, flags), detail, hint)


