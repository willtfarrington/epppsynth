# ── findings ─────────────────────────────────────────────────────────────────


@dataclass(frozen=True)
class Finding:
    """One rule violation: where it is, which rule, and what the rule means.

    Deliberately *not* the matched text. A reader locates the finding from the
    path and line; a CI log never carries the thing that leaked.
    """

    check: str
    path: str
    line: int | None
    rule: str
    detail: str
    hint: str = ""

    @property
    def where(self) -> str:
        return f"{self.path}:{self.line}" if self.line is not None else self.path

    def render(self, *, fix_hints: bool = False) -> str:
        out = f"{self.check}\t{self.where}\t{self.rule}\t{self.detail}"
        if fix_hints and self.hint:
            out += f"\n\t\thint: {self.hint}"
        return out


@dataclass
class CheckResult:
    check: str
    status: str = PASSED
    findings: list[Finding] = field(default_factory=list)
    skips: list[Skip] = field(default_factory=list)
    note: str = ""

    def fail(self) -> CheckResult:
        if self.findings:
            self.status = FAILED
        return self


@dataclass
class ScanReport:
    root: pathlib.Path
    results: list[CheckResult] = field(default_factory=list)
    history: bool = False

    @property
    def findings(self) -> list[Finding]:
        return [finding for result in self.results for finding in result.findings]

    @property
    def skips(self) -> list[Skip]:
        return [skip for result in self.results for skip in result.skips]

    @property
    def ok(self) -> bool:
        return not self.findings

    def render(self, *, fix_hints: bool = False) -> str:
        width = max(len(result.check) for result in self.results) if self.results else 0
        lines = [f"epppsynth scan - {self.root}"]
        for result in self.results:
            note = f"  {result.note}" if result.note else ""
            count = f"{len(result.findings)} finding(s)" if result.findings else ""
            lines.append(f"  {result.check:<{width}}  {result.status:<7}{note}  {count}".rstrip())
        lines.append("")
        if self.findings:
            lines.append(f"{len(self.findings)} finding(s) - check id, path:line, rule, meaning:")
            lines.extend(finding.render(fix_hints=fix_hints) for finding in self.findings)
            lines.append("")
        lines.append(
            f"{len(self.skips)} skipped line(s), by reason - every exemption, inventoried:"
        )
        by_reason: dict[str, dict[str, set[int]]] = {}
        for skip in self.skips:
            paths = by_reason.setdefault(skip.reason, {})
            numbers = paths.setdefault(skip.path, set())
            if skip.line is not None:
                numbers.add(skip.line)
        for reason in sorted(by_reason):
            entries = by_reason[reason]
            unique = sum(max(len(numbers), 1) for numbers in entries.values())
            suppressed = sum(1 for skip in self.skips if skip.reason == reason)
            counts = f"{unique} line(s)"
            if suppressed != unique:
                counts += f", {suppressed} suppression(s)"
            lines.append(f"  {reason}: {counts} - {SKIP_REASONS.get(reason, '')}".rstrip())
            for path in sorted(entries):
                numbers = ",".join(str(number) for number in sorted(entries[path]))
                lines.append(f"    {path}{':' + numbers if numbers else ''}")
        return "\n".join(lines)


